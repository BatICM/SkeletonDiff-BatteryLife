def merge_and_preprocess_data(batch1, batch2, batch3):
    """整合与预处理数据"""
    print("\n" + "=" * 60)
    print("【步骤2】数据整合与预处理")
    print("=" * 60)
    
    # 剔除Batch1中的坏点
    bad_keys_b1 = ['b1c8', 'b1c10', 'b1c12', 'b1c13', 'b1c22']
    for bk in bad_keys_b1:
        if bk in batch1:
            del batch1[bk]
    
    # Batch1和Batch2拼接
    batch2_keys = ['b2c7', 'b2c8', 'b2c9', 'b2c15', 'b2c16']
    batch1_keys = ['b1c0', 'b1c1', 'b1c2', 'b1c3', 'b1c4']
    add_len = [662, 981, 1060, 208, 482]
    
    for i, bk in enumerate(batch1_keys):
        if bk in batch1:
            batch1[bk]['cycle_life'] = batch1[bk]['cycle_life'] + add_len[i]
            for j in batch1[bk]['summary'].keys():
                if j == 'cycle':
                    batch1[bk]['summary'][j] = np.hstack((
                        batch1[bk]['summary'][j],
                        batch2[batch2_keys[i]]['summary'][j] + len(batch1[bk]['summary'][j])
                    ))
                else:
                    batch1[bk]['summary'][j] = np.hstack((
                        batch1[bk]['summary'][j],
                        batch2[batch2_keys[i]]['summary'][j]
                    ))
            last_cycle = len(batch1[bk]['cycles'].keys())
            for j, jk in enumerate(batch2[batch2_keys[i]]['cycles'].keys()):
                batch1[bk]['cycles'][str(last_cycle + j)] = batch2[batch2_keys[i]]['cycles'][jk]
    
    for bk in batch2_keys:
        if bk in batch2:
            del batch2[bk]
    
    # 剔除Batch3中的坏点
    bad_keys_b3 = ['b3c37', 'b3c2', 'b3c23', 'b3c32', 'b3c42', 'b3c43']
    for bk in bad_keys_b3:
        if bk in batch3:
            del batch3[bk]
    
    # 合并所有数据
    bat_dict = {**batch1, **batch2, **batch3}
    print(f"合并后总电池数: {len(bat_dict)}")
    
    # 数据清洗
    print("\n开始数据清洗...")
    cleaned_bat_dict = {}
    NOMINAL_CAPACITY = 1.1
    
    for key in bat_dict.keys():
        summary = bat_dict[key]['summary']
        
        if 'QD' not in summary or 'cycle' not in summary:
            continue
        
        cycles = np.array(summary['cycle'])
        capacity = np.array(summary['QD'])
        
        capacity_clean = capacity.copy()
        capacity_clean[capacity_clean > 1.3] = np.nan
        capacity_clean[capacity_clean < 0.1] = np.nan
        
        if np.isnan(capacity_clean).any():
            valid_mask = ~np.isnan(capacity_clean)
            if np.sum(valid_mask) < 10:
                continue
            f = interp1d(cycles[valid_mask], capacity_clean[valid_mask],
                        kind='linear', fill_value="extrapolate")
            capacity_filled = f(cycles)
        else:
            capacity_filled = capacity_clean
        
        capacity_med = medfilt(capacity_filled, kernel_size=5)
        window_len = min(51, len(capacity_med) // 2 * 2 + 1)
        if window_len < 3:
            continue
        capacity_smoothed = savgol_filter(capacity_med, window_length=window_len, polyorder=2)
        
        soh = (capacity_smoothed / NOMINAL_CAPACITY) * 100.0
        
        cleaned_bat_dict[key] = bat_dict[key].copy()
        cleaned_bat_dict[key]['summary']['QD'] = capacity_smoothed
        cleaned_bat_dict[key]['summary']['SOH'] = soh
        cleaned_bat_dict[key]['summary']['SOH_processed'] = soh
    
    print(f"清洗后有效电池数: {len(cleaned_bat_dict)}")
    
    return cleaned_bat_dict


