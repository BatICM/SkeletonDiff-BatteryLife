def calculate_eol_metadata(observed_cycles, observed_soh, target_length, threshold=80.0):
    """Estimate EOL from the raw observed trajectory instead of the coarse interpolation grid."""
    observed_cycles = np.asarray(observed_cycles, dtype=float).flatten()
    observed_soh = np.asarray(observed_soh, dtype=float).flatten()

    valid_mask = ~(np.isnan(observed_cycles) | np.isnan(observed_soh))
    observed_cycles = observed_cycles[valid_mask]
    observed_soh = observed_soh[valid_mask]

    if len(observed_cycles) == 0:
        return False, -1.0, 1.0

    sort_idx = np.argsort(observed_cycles)
    observed_cycles = observed_cycles[sort_idx]
    observed_soh = observed_soh[sort_idx]
    observed_cycles, unique_idx = np.unique(observed_cycles, return_index=True)
    observed_soh = observed_soh[unique_idx]

    eol_idx = np.where(observed_soh <= threshold)[0]
    if len(eol_idx) == 0:
        return False, -1.0, 1.0

    first_idx = int(eol_idx[0])
    if first_idx == 0:
        eol_cycle = float(observed_cycles[0])
    else:
        cycle_prev = float(observed_cycles[first_idx - 1])
        cycle_curr = float(observed_cycles[first_idx])
        soh_prev = float(observed_soh[first_idx - 1])
        soh_curr = float(observed_soh[first_idx])

        if abs(soh_curr - soh_prev) < 1e-8:
            eol_cycle = cycle_curr
        else:
            ratio = (threshold - soh_prev) / (soh_curr - soh_prev)
            ratio = float(np.clip(ratio, 0.0, 1.0))
            eol_cycle = cycle_prev + ratio * (cycle_curr - cycle_prev)

    target_cycle = max(float(target_length), 1.0)
    eol_cycle = float(np.clip(eol_cycle, observed_cycles[0], target_cycle))
    return True, eol_cycle, eol_cycle / target_cycle


def augment_battery_data(item, augmentation_factor=2, noise_level=0.02, 
                         scale_range=(0.95, 1.05), time_warp_ratio=0.1):
    """
    对电池数据进行增强，生成多个增强样本
    
    数据增强方法：
    1. 添加高斯噪声
    2. 幅度缩放
    3. 时间扭曲（微小的时间轴变换）
    
    Parameters:
    -----------
    item : dict
        原始电池数据字典
    augmentation_factor : int
        增强倍数，生成多少个增强样本
    noise_level : float
        噪声水平（相对于SOH范围）
    scale_range : tuple
        幅度缩放范围
    time_warp_ratio : float
        时间扭曲比例
        
    Returns:
    --------
    augmented_items : list
        增强后的数据列表
    """
    augmented_items = []
    
    for aug_idx in range(augmentation_factor):
        # 复制原始数据
        aug_item = {
            'battery_id': f"{item['battery_id']}_aug{aug_idx}",
            'source_battery_id': item.get('source_battery_id', item['battery_id']),
            'group_id': item.get('group_id'),
            'group_name': item.get('group_name'),
            'cycle_life': item['cycle_life'],
            'target_length': item['target_length'],
            'seq_length': item['seq_length'],
            'observed_seq_length': item.get('observed_seq_length'),
            'observed_max_cycle': item.get('observed_max_cycle'),
            'eol_exists': item.get('eol_exists', False),
            'eol_cycle': item.get('eol_cycle', -1.0),
            'eol_fraction': item.get('eol_fraction', 1.0),
            'extension_info': item['extension_info'].copy(),
        }
        
        # 1. SOH张量增强
        soh_tensor = item['soh_tensor'].copy()
        
        # 添加微小高斯噪声
        noise = np.random.normal(0, noise_level * 0.1, soh_tensor.shape)
        soh_aug = soh_tensor + noise.astype(np.float32)
        
        # 幅度缩放
        scale = np.random.uniform(scale_range[0], scale_range[1])
        soh_aug = soh_aug * scale
        
        # 确保范围在[-1, 1]之间
        soh_aug = np.clip(soh_aug, -1.0, 1.0).astype(np.float32)
        aug_item['soh_tensor'] = soh_aug
        
        # 2. 特征矩阵增强
        feat_matrix = item['feature_matrix'].copy()
        
        # 对特征矩阵添加微小噪声
        feat_noise = np.random.normal(0, noise_level * 0.05, feat_matrix.shape)
        feat_aug = feat_matrix + feat_noise.astype(np.float32)
        feat_aug = np.clip(feat_aug, -1.0, 1.0).astype(np.float32)
        aug_item['feature_matrix'] = feat_aug
        
        # 3. 损失掩码保持不变
        aug_item['loss_mask'] = item['loss_mask'].copy()
        
        # 4. 原始数据增强（用于可视化）
        raw_soh = item['raw_soh'].copy()
        raw_noise = np.random.normal(0, noise_level * 2, raw_soh.shape)
        raw_soh_aug = raw_soh + raw_noise
        raw_soh_aug = np.clip(raw_soh_aug, 60, 105)
        aug_item['raw_soh'] = raw_soh_aug
        aug_item['raw_cycles'] = item['raw_cycles'].copy()
        
        # 标记为增强数据
        aug_item['is_augmented'] = True
        aug_item['augmentation_idx'] = aug_idx
        
        augmented_items.append(aug_item)
    
    return augmented_items


