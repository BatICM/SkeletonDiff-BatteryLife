def _extract_raw_soh(summary_dict, nominal_capacity=1.1):
    """从原始 summary 中提取 cycle-SOH，用于原始数据集可视化。"""
    cycles = np.asarray(summary_dict.get("cycle", []), dtype=np.float64).flatten()
    qd = np.asarray(summary_dict.get("QD", []), dtype=np.float64).flatten()
    n = min(len(cycles), len(qd))
    if n < 5:
        return None, None

    cycles = cycles[:n]
    soh = (qd[:n] / nominal_capacity) * 100.0
    valid = np.isfinite(cycles) & np.isfinite(soh) & (soh >= 60.0) & (soh <= 110.0)
    if np.sum(valid) < 5:
        return None, None

    cycles = cycles[valid]
    soh = soh[valid]
    sort_idx = np.argsort(cycles)
    return cycles[sort_idx], soh[sort_idx]


